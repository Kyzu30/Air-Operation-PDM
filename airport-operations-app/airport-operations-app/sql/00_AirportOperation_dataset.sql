DROP DATABASE IF EXISTS airport_operations;
CREATE DATABASE airport_operations CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE airport_operations;
SET NAMES utf8mb4;

CREATE TABLE Passenger (
  PassportID VARCHAR(12)  NOT NULL,
  `Name`     VARCHAR(100) NOT NULL,
  Email      VARCHAR(100),
  PRIMARY KEY (PassportID)
) ENGINE=InnoDB;

CREATE TABLE PassengerPhone (
  PassportID  VARCHAR(12) NOT NULL,
  PhoneNumber VARCHAR(20) NOT NULL,
  PRIMARY KEY (PassportID, PhoneNumber),
  FOREIGN KEY (PassportID) REFERENCES Passenger (PassportID) ON DELETE CASCADE ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Airport (
  AirportCode CHAR(3)      NOT NULL,
  AirportName VARCHAR(120) NOT NULL,
  City        VARCHAR(60)  NOT NULL,
  Country     VARCHAR(60)  NOT NULL,
  PRIMARY KEY (AirportCode)
) ENGINE=InnoDB;

CREATE TABLE Aircraft (
  AircraftID VARCHAR(10) NOT NULL,
  Model      VARCHAR(50) NOT NULL,
  Capacity   INT         NOT NULL CHECK (Capacity > 0),
  PRIMARY KEY (AircraftID)
) ENGINE=InnoDB;

CREATE TABLE Gate (
  GateID   VARCHAR(10) NOT NULL,
  `Status` VARCHAR(20) NOT NULL,
  PRIMARY KEY (GateID),
  CONSTRAINT chk_gate_status CHECK (`Status` IN ('Available', 'Occupied', 'Maintenance'))
) ENGINE=InnoDB;

CREATE TABLE SecurityGate (
  GateID      VARCHAR(10) NOT NULL,
  `Type`      VARCHAR(30) NOT NULL,
  `Timestamp` DATETIME    NOT NULL,
  `Result`    VARCHAR(20) NOT NULL,
  `Target`    VARCHAR(20) NOT NULL,
  PRIMARY KEY (GateID)
) ENGINE=InnoDB;

CREATE TABLE Employee (
  EmployeeID VARCHAR(10)  NOT NULL,
  `Name`     VARCHAR(100) NOT NULL,
  Role       VARCHAR(30)  NOT NULL,
  PRIMARY KEY (EmployeeID)
) ENGINE=InnoDB;

CREATE TABLE EmployeeContact (
  EmployeeID  VARCHAR(10)  NOT NULL,
  ContactInfo VARCHAR(100) NOT NULL,
  PRIMARY KEY (EmployeeID, ContactInfo),
  FOREIGN KEY (EmployeeID) REFERENCES Employee (EmployeeID) ON DELETE CASCADE ON UPDATE RESTRICT
) ENGINE=InnoDB;

-- UPDATED: DepartureTime and ArrivalTime are scheduled times.
-- ActualDepartureTime is NULL until a departure is known to have occurred.
CREATE TABLE Flight (
  FlightID             VARCHAR(20) NOT NULL,
  `Date`               DATE        NOT NULL,
  DepartureTime        DATETIME    NOT NULL,
  ActualDepartureTime  DATETIME    NULL,
  ArrivalTime          DATETIME    NOT NULL,
  `Status`             VARCHAR(20) NOT NULL,
  DepartureAirportCode CHAR(3)     NOT NULL,
  ArrivalAirportCode   CHAR(3)     NOT NULL,
  AircraftID           VARCHAR(10) NOT NULL,
  GateID               VARCHAR(10) NOT NULL,
  PRIMARY KEY (FlightID),
  CONSTRAINT chk_flight_status CHECK (`Status` IN ('Scheduled', 'Delayed', 'Departed', 'Arrived', 'Cancelled')),
  CHECK (ArrivalTime > DepartureTime),
  CHECK (DepartureAirportCode <> ArrivalAirportCode),
  FOREIGN KEY (DepartureAirportCode) REFERENCES Airport (AirportCode) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (ArrivalAirportCode)   REFERENCES Airport (AirportCode) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (AircraftID)           REFERENCES Aircraft (AircraftID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (GateID)               REFERENCES Gate (GateID) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Ticket (
  TicketID           VARCHAR(10) NOT NULL,
  TicketPurchaseTime DATETIME    NOT NULL,
  SeatNumber         VARCHAR(5)  NOT NULL,
  `Status`           VARCHAR(20) NOT NULL,
  PassportID         VARCHAR(12) NOT NULL,
  FlightID           VARCHAR(20) NOT NULL,
  PRIMARY KEY (TicketID),
  CONSTRAINT chk_ticket_status CHECK (`Status` IN ('Confirmed', 'Checked-in', 'Boarded', 'No-show', 'Cancelled')),
  UNIQUE (FlightID, SeatNumber),
  FOREIGN KEY (PassportID) REFERENCES Passenger (PassportID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (FlightID)   REFERENCES Flight (FlightID) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Luggage (
  PassportID VARCHAR(12)  NOT NULL,
  LuggageID  VARCHAR(10)  NOT NULL,
  Weight     DECIMAL(5,1) NOT NULL CHECK (Weight > 0),
  `Status`   VARCHAR(20)  NOT NULL,
  FlightID   VARCHAR(20)  NOT NULL,
  PRIMARY KEY (PassportID, LuggageID),
  CONSTRAINT chk_luggage_status CHECK (`Status` IN ('Checked-in', 'Loaded', 'Delivered', 'Delayed', 'Lost')),
  FOREIGN KEY (PassportID) REFERENCES Passenger (PassportID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (FlightID)   REFERENCES Flight (FlightID) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

-- NEW: Event history by baggage item.
CREATE TABLE LuggageEvent (
  PassportID VARCHAR(12) NOT NULL,
  LuggageID  VARCHAR(10) NOT NULL,
  EventType  VARCHAR(20) NOT NULL,
  EventTime  DATETIME    NOT NULL,
  PRIMARY KEY (PassportID, LuggageID, EventType, EventTime),
  FOREIGN KEY (PassportID, LuggageID) REFERENCES Luggage (PassportID, LuggageID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CHECK (EventType IN ('Checked-in', 'Loaded', 'Delivered', 'Delayed', 'Lost'))
) ENGINE=InnoDB;

CREATE TABLE FlightEmployee (
  FlightID   VARCHAR(20) NOT NULL,
  EmployeeID VARCHAR(10) NOT NULL,
  PRIMARY KEY (FlightID, EmployeeID),
  FOREIGN KEY (FlightID)   REFERENCES Flight (FlightID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (EmployeeID) REFERENCES Employee (EmployeeID) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE PassengerSecurityGate (
  PassportID     VARCHAR(12) NOT NULL,
  SecurityGateID VARCHAR(10) NOT NULL,
  PRIMARY KEY (PassportID, SecurityGateID),
  FOREIGN KEY (PassportID)     REFERENCES Passenger (PassportID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (SecurityGateID) REFERENCES SecurityGate (GateID) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE LuggageSecurityGate (
  PassportID     VARCHAR(12) NOT NULL,
  LuggageID      VARCHAR(10) NOT NULL,
  SecurityGateID VARCHAR(10) NOT NULL,
  PRIMARY KEY (PassportID, LuggageID, SecurityGateID),
  FOREIGN KEY (PassportID, LuggageID) REFERENCES Luggage (PassportID, LuggageID) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (SecurityGateID)        REFERENCES SecurityGate (GateID) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

-- Indexes for scheduled-date lookups and actual-departure ranges.
CREATE INDEX idx_flight_date ON Flight (`Date`);
CREATE INDEX idx_flight_actual_departure_time ON Flight (ActualDepartureTime);

